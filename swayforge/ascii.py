def block(text: str, fill: str = "█") -> list[str]:
    """Tiny 5-row block letters – the fallback when nothing else fits."""
    rows = ["", "", "", "", ""]
    for ch in text.upper():
        glyph = FONT.get(ch, FONT["?"])
        for i in range(5):
            rows[i] += glyph[i].replace("█", fill) + " "
    return [r.rstrip() for r in rows]


@lru_cache(maxsize=1)
def _atlas() -> dict:
    try:
        return json.loads((ART_DIR / "banner.json").read_text())
    except (OSError, ValueError):
        return {}


def banner(text: str, rows: int = 5) -> list[str]:
    """Shaded capital letters (@%#* core, .:-=+ edges), 4–8 rows tall."""
    font = _atlas().get(str(rows))
    if not font:
        return block(text, "#")
    out = [""] * rows
    for i, ch in enumerate(text):
        g = font.get(ch.upper()) or font.get("?")
        w = max(len(x) for x in g)
        for r in range(rows):
            out[r] += (" " if i else "") + g[r].ljust(w)
    out = [l.rstrip() for l in out]
    while out and not out[-1].strip():
        out.pop()
    while out and not out[0].strip():
        out.pop(0)
    return out


def best_banner(text: str, max_cols: int = 80) -> list[str]:
    """The tallest banner that fits into max_cols, else the tiny block font."""
    for rows in (8, 7, 6, 5, 4):
        b = banner(text, rows)
        if max(map(len, b), default=0) <= max_cols:
            return b
    return block(text, "#")


def layers(lines: list[str]) -> tuple[list[str], list[str]]:
    """Split art into (face, shade) layers of equal size – for two-colour rendering."""
    face = ["".join(" " if ch in SHADE else ch for ch in l) for l in lines]
    shade = ["".join(ch if ch in SHADE else " " for ch in l) for l in lines]
    return face, shade


# ── Motifs ───────────────────────────────────────────────────────────
@lru_cache(maxsize=1)
def _bundled() -> dict[str, str]:
    return {f.stem: "\n" + f.read_text().rstrip("\n") + "\n" for f in sorted(ART_DIR.glob("*.txt"))}


ART_NAMES = ("forge", "anvil", "bat", "moon", "rose", "skull", "lantern", "crt", "terminal",
             "gamepad", "cyberdeck", "wired", "rosewindow")


def user_art() -> dict[str, str]:
    out = {}
    dirs = [getattr(paths, "SWAYFORGE_ASCII", None), paths.CONFIG_DIR / "ascii"]
    for d in dirs:
        if d and d.is_dir():
            for f in sorted(d.glob("*.txt")):
                out[f.stem] = "\n" + f.read_text().rstrip("\n") + "\n"
    return out


def all_art() -> dict[str, str]:
    return _bundled() | user_art()


def art(name: str) -> list[str]:
    arts = all_art()
    a = arts.get(name) or arts.get("forge") or "\n?\n"
    lines = a.strip("\n").split("\n")
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    return [l[pad:].rstrip() for l in lines]


def resolve(s: dict, theme) -> str:
    """Which art is active: explicit choice or the theme's motif."""
    choice = s["theme"].get("ascii", "auto")
    if choice and choice != "auto" and choice in all_art():
        return choice
    return theme.style.get("ascii", "forge")


def _two_tone(line: str, main: str = "$1", shade: str = "$3") -> str:
    out, cur = [main], main
    for ch in line:
        want = shade if ch in SHADE else main
        if ch != " " and want != cur:
            out.append(want)
            cur = want
        out.append(ch)
    return "".join(out)


def fastfetch_logo(name: str) -> str:
    """Logo file for fastfetch: $1 = main colour, $3 = shading, $2 = caption line."""
    lines = art(name)
    out = []
    for i, l in enumerate(lines):
        if i == len(lines) - 1 and l.strip().startswith("["):
            out.append("$2" + l)
        else:
            out.append(_two_tone(l))
    return "\n".join(out) + "\n"
