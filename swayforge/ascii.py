def block(text: str, fill: str = "█") -> list[str]:
    """Tiny 5-row block letters – the fallback when nothing else fits."""
    rows = ["", "", "", "", ""]
    for ch in text.upper():
        glyph = FONT.get(ch, FONT["?"])
        for i in range(5):
            rows[i] += glyph[i].replace("█", fill) + " "
    return [r.rstrip() for r in rows]


@lru_cache(maxsize=1)
def _atlas() -> dict:
    try:
        return json.loads((ART_DIR / "banner.json").read_text())
    except (OSError, ValueError):
        return {}


def banner(text: str, rows: int = 5) -> list[str]:
    """Shaded capital letters (@%#* core, .:-=+ edges), 4–8 rows tall."""
    font = _atlas().get(str(rows))
    if not font:
        return block(text, "#")
    out = [""] * rows
    for i, ch in enumerate(text):
        g = font.get(ch.upper()) or font.get("?")
        w = max(len(x) for x in g)
        for r in range(rows):
            out[r] += (" " if i else "") + g[r].ljust(w)
    out = [l.rstrip() for l in out]
    while out and not out[-1].strip():
        out.pop()
    while out and not out[0].strip():
        out.pop(0)
    return out


